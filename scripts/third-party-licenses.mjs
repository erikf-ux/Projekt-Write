#!/usr/bin/env node
/**
 * Writes THIRD-PARTY-LICENSES: every third-party component that ships with
 * Project Write, with version and declared licence (master prompt, section 7).
 *
 * * Rust: normal (non-dev, non-build) dependencies for all target platforms,
 *   default features only – the optional test plugin is therefore excluded.
 * * npm: production dependencies (`npm query .prod`).
 *
 * The output is deterministic so CI can verify that the committed file is
 * current: `node scripts/third-party-licenses.mjs && git diff --exit-code`.
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const isWindows = process.platform === 'win32';

function run(command, args, { shell = false } = {}) {
  // Only npm needs a shell on Windows (npm.cmd). cargo runs without one, so
  // characters such as "|" in its arguments are never interpreted.
  return execFileSync(command, args, { cwd: root, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024, shell });
}

function rustComponents() {
  // `cargo tree` applies the real feature resolver (cargo metadata over-approximates).
  const output = run('cargo', [
    'tree',
    '--color',
    'never',
    '--locked',
    '--manifest-path',
    'src-tauri/Cargo.toml',
    '--edges',
    'normal',
    '--target',
    'all',
    '--prefix',
    'none',
    '--format',
    '{p}|{l}',
  ]);
  const components = new Map();
  // Strip ANSI escape sequences in case a CARGO_TERM_COLOR setting wins anyway.
  // eslint-disable-next-line no-control-regex
  const plain = output.replace(/\u001b\[[0-9;]*m/g, '');
  for (const line of plain.split(/\r?\n/)) {
    // Repeated subtrees end with " (*)"; local path dependencies carry "(path)".
    const match = /^(\S+) v(\S+)(?: \([^)]*\))?\|(.*?)(?: \(\*\))?$/.exec(line.trim());
    if (!match) {
      continue;
    }
    const [, name, version, license] = match;
    if (name === 'project-write') {
      continue;
    }
    components.set(`${name}@${version}`, { name, version, license: license.trim() || 'see crate' });
  }
  return [...components.values()];
}

function npmComponents() {
  const packages = JSON.parse(run('npm', ['query', '.prod'], { shell: isWindows }));
  return packages
    .filter((pkg) => pkg.location !== '')
    .map((pkg) => ({ name: pkg.name, version: pkg.version, license: pkg.license ?? 'UNKNOWN' }));
}

function table(components) {
  const sorted = [...components].sort(
    (a, b) => a.name.localeCompare(b.name, 'en') || a.version.localeCompare(b.version, 'en'),
  );
  const unique = sorted.filter(
    (c, i) => i === 0 || c.name !== sorted[i - 1].name || c.version !== sorted[i - 1].version,
  );
  const width = Math.max(...unique.map((c) => `${c.name} ${c.version}`.length));
  return unique.map((c) => `${`${c.name} ${c.version}`.padEnd(width)}  ${c.license}`).join('\n');
}

function summary(components) {
  const counts = new Map();
  for (const c of components) {
    counts.set(c.license, (counts.get(c.license) ?? 0) + 1);
  }
  return [...counts.entries()]
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0], 'en'))
    .map(([license, count]) => `  ${String(count).padStart(4)}  ${license}`)
    .join('\n');
}

const rust = rustComponents();
const npm = npmComponents();

const text = `Project Write – third-party components
======================================

Generated by scripts/third-party-licenses.mjs. Do not edit by hand.

This list names every third-party component shipped with Project Write and the
licence it declares. Full licence texts are bundled with the installers
(Phase 14). Dictionaries (GPL, e.g. igerman98) are never compiled into the
program; they ship as separate data packages with their own licence text
(master prompt, section 7). Phase 1 ships no dictionaries.

Rust crates (normal dependencies, all target platforms): ${rust.length}
Licence summary:
${summary(rust)}

npm packages (production dependencies): ${npm.length}
Licence summary:
${summary(npm)}


Rust crates
-----------
${table(rust)}


npm packages
------------
${table(npm)}
`;

writeFileSync(path.join(root, 'THIRD-PARTY-LICENSES'), text);
console.log(`THIRD-PARTY-LICENSES: ${rust.length} crates, ${npm.length} npm packages`);
