#!/usr/bin/env node
/**
 * Writes THIRD-PARTY-LICENSES: every third-party component that ships with
 * Project Write, with version and declared licence (master prompt, section 7).
 *
 * * Rust: normal (non-dev, non-build) dependencies for all target platforms,
 *   default features only – the optional test plugin is therefore excluded.
 * * npm: production dependencies (`npm query .prod`), without packages that
 *   only serve Node.js and never reach the bundle (`NOT_SHIPPED`).
 *
 * The output is deterministic so CI can verify that the committed file is
 * current: `node scripts/third-party-licenses.mjs && git diff --exit-code`.
 */
import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const isWindows = process.platform === 'win32';

function run(command, args, { shell = false } = {}) {
  // Only npm needs a shell on Windows (npm.cmd). cargo runs without one, so
  // characters such as "|" in its arguments are never interpreted.
  return execFileSync(command, args, { cwd: root, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024, shell });
}

function rustComponents() {
  // `cargo tree` applies the real feature resolver (cargo metadata over-approximates).
  const output = run('cargo', [
    'tree',
    '--color',
    'never',
    '--locked',
    '--manifest-path',
    'src-tauri/Cargo.toml',
    '--edges',
    'normal',
    '--target',
    'all',
    '--prefix',
    'none',
    '--format',
    '{p}|{l}',
  ]);
  const components = new Map();
  // Strip ANSI escape sequences in case a CARGO_TERM_COLOR setting wins anyway.
  // eslint-disable-next-line no-control-regex
  const plain = output.replace(/\u001b\[[0-9;]*m/g, '');
  for (const line of plain.split(/\r?\n/)) {
    // Repeated subtrees end with " (*)"; local path dependencies carry "(path)".
    const match = /^(\S+) v(\S+)(?: \([^)]*\))?\|(.*?)(?: \(\*\))?$/.exec(line.trim());
    if (!match) {
      continue;
    }
    const [, name, version, license] = match;
    if (name === 'project-write') {
      continue;
    }
    components.set(`${name}@${version}`, { name, version, license: license.trim() || 'see crate' });
  }
  return [...components.values()];
}

/**
 * Production packages that do not ship: `@napi-rs/canvas` is an optional
 * dependency of `pdfjs-dist` for rendering under Node.js; the app bundle
 * never imports it (ADR 0019). npm installs a different native variant per
 * platform, so listing it would also make this file depend on the machine.
 */
const NOT_SHIPPED = [/^@napi-rs\/canvas(-.+)?$/];

function npmComponents() {
  const packages = JSON.parse(run('npm', ['query', '.prod'], { shell: isWindows }));
  return packages
    .filter((pkg) => pkg.location !== '')
    .filter((pkg) => !NOT_SHIPPED.some((pattern) => pattern.test(pkg.name)))
    .map((pkg) => ({ name: pkg.name, version: pkg.version, license: pkg.license ?? 'UNKNOWN' }));
}

function table(components) {
  const sorted = [...components].sort(
    (a, b) => a.name.localeCompare(b.name, 'en') || a.version.localeCompare(b.version, 'en'),
  );
  const unique = sorted.filter(
    (c, i) => i === 0 || c.name !== sorted[i - 1].name || c.version !== sorted[i - 1].version,
  );
  const width = Math.max(...unique.map((c) => `${c.name} ${c.version}`.length));
  return unique.map((c) => `${`${c.name} ${c.version}`.padEnd(width)}  ${c.license}`).join('\n');
}

function summary(components) {
  const counts = new Map();
  for (const c of components) {
    counts.set(c.license, (counts.get(c.license) ?? 0) + 1);
  }
  return [...counts.entries()]
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0], 'en'))
    .map(([license, count]) => `  ${String(count).padStart(4)}  ${license}`)
    .join('\n');
}

// Dictionaries (Phase 12, ADR 0024): data packages next to the program.
const DICTIONARIES = [
  {
    name: 'de-DE, de-AT, de-CH (igerman98 20161207)',
    license: 'GPL-2.0-or-later (affix files GPL-2.0 and GPL-3.0)',
  },
  { name: 'en-US (SCOWL 2020.12.07)', license: 'SCOWL licence (permissive, see en-US/LICENSE)' },
  {
    name: 'en-GB (libreoffice-dictionaries 24.2.1)',
    license: 'SCOWL licence per Debian, LGPL per its README (see en-GB/LICENSE)',
  },
];

const rust = rustComponents();
const npm = npmComponents();

const text = `Project Write – third-party components
======================================

Generated by scripts/third-party-licenses.mjs. Do not edit by hand.

This list names every third-party component shipped with Project Write and the
licence it declares. The full licence texts and copyright notices are in
THIRD-PARTY-NOTICES, which ships with the installers (Phase 14). Dictionaries are never compiled into the program; they ship as
separate data packages in dictionaries/<language>/ with their own licence text
(master prompt, section 7). The source of igerman98 lies in
dictionaries/sources/.

Rust crates (normal dependencies, all target platforms): ${rust.length}
Licence summary:
${summary(rust)}

npm packages (production dependencies): ${npm.length}
Licence summary:
${summary(npm)}


Rust crates
-----------
${table(rust)}


npm packages
------------
${table(npm)}


Dictionaries (data packages)
----------------------------
${DICTIONARIES.map((d) => `${d.name.padEnd(44)}${d.license}`).join('\n')}
`;

writeFileSync(path.join(root, 'THIRD-PARTY-LICENSES'), text);
console.log(`THIRD-PARTY-LICENSES: ${rust.length} crates, ${npm.length} npm packages`);

// ---------------------------------------------------------------------------
// THIRD-PARTY-NOTICES (Phase 14, ADR 0028): the full licence texts and
// copyright notices of every component above, as their packages ship them.
// The same text is printed once, with all components that carry it. A
// package without a licence file gets the standard text of a licence it
// offers (scripts/licenses/), with its authors from the package metadata.

const LICENCE_FILE = /^(licen[cs]e|copying|notice|copyright|unlicense|authors)([-._].*)?$/i;

/** The standard texts, in the order of preference for an "A OR B" choice. */
const STANDARD = ['MIT', 'Apache-2.0', 'BSD-3-Clause', 'MPL-2.0'];

function readNormalized(file) {
  return readFileSync(file, 'utf8').replace(/^\uFEFF/, '').replace(/\r\n?/g, '\n').replace(/\s+$/, '');
}

/** The licence files of a package directory, sorted, as normalized text. */
function licenceTexts(dir) {
  let entries;
  try {
    entries = readdirSync(dir, { withFileTypes: true });
  } catch {
    return [];
  }
  return entries
    .filter((entry) => entry.isFile() && LICENCE_FILE.test(entry.name))
    .map((entry) => entry.name)
    .sort((a, b) => a.localeCompare(b, 'en'))
    .map((name) => readNormalized(path.join(dir, name)))
    .filter((content) => content.length > 0);
}

/** The standard text a package without licence files is used under. */
function standardChoice(expression) {
  const offered = expression.split(/\s+(?:OR|AND)\s+|\//).map((id) => id.replace(/[()]/g, '').trim());
  return STANDARD.find((id) => offered.includes(id)) ?? null;
}

function rustDirectories() {
  const metadata = JSON.parse(
    run('cargo', [
      'metadata',
      '--format-version',
      '1',
      '--locked',
      '--manifest-path',
      'src-tauri/Cargo.toml',
    ]),
  );
  const dirs = new Map();
  for (const pkg of metadata.packages) {
    dirs.set(`${pkg.name}@${pkg.version}`, {
      dir: path.dirname(pkg.manifest_path),
      authors: pkg.authors ?? [],
    });
  }
  return dirs;
}

function npmDirectories() {
  const packages = JSON.parse(run('npm', ['query', '.prod'], { shell: isWindows }));
  const dirs = new Map();
  for (const pkg of packages) {
    const author = typeof pkg.author === 'string' ? pkg.author : pkg.author?.name;
    dirs.set(`${pkg.name}@${pkg.version}`, {
      dir: pkg.realpath ?? pkg.path,
      authors: author ? [author] : [],
    });
  }
  return dirs;
}

function notices() {
  const rustDirs = rustDirectories();
  const npmDirs = npmDirectories();
  /** text -> components that ship it */
  const byText = new Map();
  const standardUse = new Map();
  const add = (content, component) => {
    const list = byText.get(content) ?? [];
    list.push(component);
    byText.set(content, list);
  };
  const missing = [];
  const visit = (components, dirs) => {
    for (const c of components) {
      const label = `${c.name} ${c.version}`;
      const info = dirs.get(`${c.name}@${c.version}`);
      const texts = info ? licenceTexts(info.dir) : [];
      if (texts.length > 0) {
        for (const content of texts) {
          add(content, label);
        }
        continue;
      }
      const choice = standardChoice(c.license);
      if (!choice) {
        missing.push(`${label} (${c.license})`);
        continue;
      }
      const authors = info?.authors.length ? info.authors.join(', ') : 'the authors of the package';
      const list = standardUse.get(choice) ?? [];
      list.push(`${label} – ${c.license}, used under ${choice}; copyright ${authors}`);
      standardUse.set(choice, list);
    }
  };
  visit(rust, rustDirs);
  visit(npm, npmDirs);
  if (missing.length > 0) {
    throw new Error(`no licence text for: ${missing.join(', ')}`);
  }
  const unique = (list) => [...new Set(list)].sort((a, b) => a.localeCompare(b, 'en'));
  const blocks = [...byText.entries()]
    .map(([content, components]) => ({ components: unique(components), content }))
    .sort(
      (a, b) =>
        a.components[0].localeCompare(b.components[0], 'en') || a.content.localeCompare(b.content, 'en'),
    );
  const rule = '='.repeat(78);
  const parts = blocks.map(
    (block) => `${rule}\n${block.components.join('\n')}\n${rule}\n\n${block.content}\n`,
  );
  const standard = [...standardUse.entries()]
    .sort((a, b) => STANDARD.indexOf(a[0]) - STANDARD.indexOf(b[0]))
    .map(
      ([id, users]) =>
        `${rule}\nStandard text ${id}, for packages that ship no licence file:\n${unique(users).join('\n')}\n${rule}\n\n${readNormalized(path.join(root, 'scripts', 'licenses', `${id}.txt`))}\n`,
    );
  return `Project Write – licence texts and notices of third-party components
====================================================================

Generated by scripts/third-party-licenses.mjs. Do not edit by hand.

The full licence texts and copyright notices of the components listed in
THIRD-PARTY-LICENSES, as their packages ship them. Each text is printed once,
headed by the components that carry it. The dictionaries carry their own
licence texts in dictionaries/<language>/LICENSE.

${parts.join('\n')}
${standard.join('\n')}`;
}

writeFileSync(path.join(root, 'THIRD-PARTY-NOTICES'), notices());
console.log('THIRD-PARTY-NOTICES written');
